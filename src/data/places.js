/** Best known location panel for a drop source, or null when data is silent. */
export function placeForSource(source) {
  if (!source) return null;
  const direct =
    containers[source.id] || bags[source.id] || source.place || null;
  if (direct)
    return placePanels[direct] ? { key: direct, ...placePanels[direct] } : null;
  const biome = (source.biomes || []).find((b) => biomes[b]);
  if (biome) return { key: biomes[biome], ...placePanels[biomes[biome]] };
  const event = (source.events || []).find((e) => events[e]);
  if (event) return { key: events[event], ...placePanels[event], event: true };
  return null;
}
